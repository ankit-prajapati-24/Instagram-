@dataclass
class ClipQuery:
    """Structured visual search query generated by LLM."""
    clip_index: int
    search_query: str
    shot_intent: str

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class VideoFileCandidate:
    """Represents a specific video quality/resolution file from Pexels."""
    id: int
    quality: str
    file_type: str
    width: int
    height: int
    fps: float
    link: str

    @property
    def resolution(self) -> str:
        return f"{self.width}x{self.height}"

    @property
    def is_portrait(self) -> bool:
        return self.height >= self.width

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class PexelsVideo:
    """Metadata for a matched Pexels video."""
    id: int
    url: str
    duration: int
    tags: List[str]
    user_name: str
    selected_file: Optional[VideoFileCandidate]
    was_fallback: bool = False

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "url": self.url,
            "duration": self.duration,
            "tags": self.tags,
            "user_name": self.user_name,
            "selected_file": self.selected_file.to_dict() if self.selected_file else None,
            "was_fallback": self.was_fallback,
        }


@dataclass
class ClipMatch:
    """A matched segment pairing the generated query with Pexels footage."""
    clip_index: int
    query: ClipQuery
    video: Optional[PexelsVideo]
    download_path: Optional[str] = None
    error: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "clip_index": self.clip_index,
            "query": self.query.to_dict(),
            "video": self.video.to_dict() if self.video else None,
            "download_path": self.download_path,
            "error": self.error,
        }


@dataclass
class StockMatcherResult:
    """Overall outcome of the stock matching process."""
    script_segment: str
    duration_seconds: float
    clip_count: int
    model_used: str
    matches: List[ClipMatch] = field(default_factory=list)
    execution_time_seconds: float = 0.0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "script_segment": self.script_segment,
            "duration_seconds": self.duration_seconds,
            "clip_count": self.clip_count,
            "model_used": self.model_used,
            "execution_time_seconds": round(self.execution_time_seconds, 2),
            "matches": [m.to_dict() for m in self.matches],
        }

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), indent=indent)


