def main() -> int:
    parser = argparse.ArgumentParser(
        description="AI-Powered Stock Video Matcher: Convert narration into high-res stock video cuts."
    )
    parser.add_argument(
        "script",
        nargs="?",
        help="Voiceover script segment (or specify via -s / --script).",
    )
    parser.add_argument(
        "-s",
        "--script-text",
        dest="script_flag",
        help="Voiceover script string directly.",
    )
    parser.add_argument(
        "-f",
        "--script-file",
        help="Path to a text file containing the script segment.",
    )
    parser.add_argument(
        "-d",
        "--duration",
        type=float,
        default=7.5,
        help="Voiceover duration in seconds (default: 7.5s -> 3 cuts).",
    )
    parser.add_argument(
        "--download",
        action="store_true",
        help="Download matched MP4 clips to output directory.",
    )
    parser.add_argument(
        "-o",
        "--output-dir",
        default="output_clips",
        help="Directory to save downloaded clips (default: output_clips).",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        dest="output_json",
        help="Output raw JSON format to stdout.",
    )
    parser.add_argument(
        "--model",
        help="Override OmniRoute model name (e.g. agy/gemini-3.7-flash-medium).",
    )
    parser.add_argument(
        "--base-url",
        help="Override OmniRoute base URL.",
    )
    parser.add_argument(
        "--mock",
        "--dry-run",
        action="store_true",
        dest="mock",
        help="Run in mock/offline mode (simulates OmniRoute AI queries and Pexels video metadata).",
    )

    args = parser.parse_args()

    # Determine script content
    script_content = ""
    if args.script_file:
        file_path = Path(args.script_file)
        if not file_path.exists():
            print(f"Error: Script file not found: {args.script_file}", file=sys.stderr)
            return 1
        script_content = file_path.read_text(encoding="utf-8").strip()
    elif args.script_flag:
        script_content = args.script_flag.strip()
    elif args.script:
        script_content = args.script.strip()
    else:
        # Default sample script for fast testing
        script_content = (
            "Deep inside the Swiss Alps lies an ultra-secure subterranean vault, "
            "where billionaires store metric tons of pure gold bars behind twenty-ton blast doors."
        )

    console = Console() if RICH_AVAILABLE else None

    # Check Pexels API key early
    pexels_key = os.getenv("PEXELS_API_KEY")
    if not pexels_key and not args.mock:
        msg = (
            "Notice: PEXELS_API_KEY is not set in environment or .env file.\n"
            "Query generation will succeed, but video search requires a free Pexels key from https://www.pexels.com/api/\n"
            "(Tip: Use --mock to test full visual rendering and downloads offline)."
        )
        if console and not args.output_json:
            console.print(f"[bold yellow]{msg}[/bold yellow]\n")
        else:
            print(msg, file=sys.stderr)

    try:
        agent = StockVideoMatcherAgent(
            omniroute_base_url=args.base_url,
            omniroute_model=args.model,
            pexels_api_key=pexels_key,
        )

        status_msg = (
            "[bold cyan]Generating visual queries via OmniRoute...[/bold cyan]"
            if not args.mock
            else "[bold cyan]Generating mock visual queries and stock video matches...[/bold cyan]"
        )

        # Execute query generation & matching
        if console and not args.output_json:
            with console.status(status_msg):
                result = agent.match(
                    script_segment=script_content,
                    duration_seconds=args.duration,
                    download=False,
                    output_dir=args.output_dir,
                    mock=args.mock,
                )
        else:
            result = agent.match(
                script_segment=script_content,
                duration_seconds=args.duration,
                download=False,
                output_dir=args.output_dir,
                mock=args.mock,
            )

        # Handle downloads with Rich progress if requested
        if args.download:
            # The CLI downloads outside match() (it wants a Rich progress
            # bar per clip), so it names --output-dir itself. match() used
            # to leave the destination on agent.downloader as a side
            # effect; it no longer does, because that shared mutation raced
            # when match() is called concurrently.
            clips_to_download = [m for m in result.matches if m.video and m.video.selected_file]
            if clips_to_download:
                if console and not args.output_json:
                    with Progress(
                        SpinnerColumn(),
                        TextColumn("[progress.description]{task.description}"),
                        BarColumn(),
                        DownloadColumn(),
                        TransferSpeedColumn(),
                        TimeRemainingColumn(),
                        console=console,
                    ) as progress:
                        for m in clips_to_download:
                            task = progress.add_task(
                                f"Downloading clip_{m.clip_index:02d}.mp4",
                                total=None,
                            )
                            try:
                                saved_path = agent.downloader.download_clip(
                                    url=m.video.selected_file.link,
                                    clip_index=m.clip_index,
                                    progress=progress,
                                    task_id=task,
                                    output_dir=args.output_dir,
                                )
                                m.download_path = str(saved_path)
                            except Exception as err:
                                m.error = f"Download failed: {err}"
                else:
                    for m in clips_to_download:
                        try:
                            saved_path = agent.downloader.download_clip(
                                url=m.video.selected_file.link,
                                clip_index=m.clip_index,
                                output_dir=args.output_dir,
                            )
                            m.download_path = str(saved_path)
                        except Exception as err:
                            m.error = f"Download failed: {err}"

        # Output format
        if args.output_json or not RICH_AVAILABLE:
            print(result.to_json(indent=2))
        else:
            render_rich_output(console, result, show_downloads=args.download)

        return 0

    except Exception as err:
        if args.output_json:
            print(json.dumps({"error": str(err)}, indent=2), file=sys.stderr)
        elif console:
            console.print(f"[bold red]Execution Error:[/bold red] {err}")
        else:
            print(f"Error: {err}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
