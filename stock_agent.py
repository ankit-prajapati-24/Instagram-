# The renderer's output frame size, in pixels (1080x1920). This MUST match
# engine/media rendering's actual output resolution: every downloaded clip is
# scaled to this size before compositing, so picking a source file far above
# it only burns bandwidth/disk/CPU on pixels that get thrown away, and picking
# one below it forces an upscale that never looks as good as a downscale.
RENDER_TARGET_WIDTH = 1080
RENDER_TARGET_HEIGHT = 1920
RENDER_TARGET_PIXELS = RENDER_TARGET_WIDTH * RENDER_TARGET_HEIGHT  # 2,073,600

# _select_best_video scoring bands (see the resolution-scoring comment
# there for the full rationale). The orientation bonus must stay the
# dominant term: a correctly-oriented file must outscore a wrongly-oriented
# one no matter what the other terms award. Those other terms are the
# resolution score AND the HD-quality bonus, and they are summed, so the
# comparison that matters is against their combined maximum
# (_RESOLUTION_COVER_CEILING + _HD_QUALITY_BONUS = 4,500,000), not against
# the resolution term alone. Real headroom under ORIENTATION_BONUS is
# 500,000. Within the resolution term, the "covers the target" band is
# [_RESOLUTION_COVER_FLOOR, _RESOLUTION_COVER_CEILING] = [2,000,000,
# 4,000,000] and the "undersized" band is [0, _RESOLUTION_UNDERSIZED_CEILING)
# = [0, 1,000,000) — the bands don't overlap, so every covering file
# outscores every undersized one.
#
# These asserts document the invariants; note they are stripped under
# `python -O`, so they are a statement of intent for whoever edits the
# numbers, not a runtime guard. Keep them honest.
ORIENTATION_BONUS = 5_000_000.0
_RESOLUTION_COVER_CEILING = 4_000_000.0
_RESOLUTION_COVER_FLOOR = 2_000_000.0
_RESOLUTION_UNDERSIZED_CEILING = 1_000_000.0
# Awarded on top of the resolution score when Pexels flags a file "hd".
_HD_QUALITY_BONUS = 500_000.0
assert _RESOLUTION_COVER_CEILING + _HD_QUALITY_BONUS < ORIENTATION_BONUS
assert _RESOLUTION_UNDERSIZED_CEILING < _RESOLUTION_COVER_FLOOR < _RESOLUTION_COVER_CEILING


class PexelsFetcher:
    """Queries Pexels Videos API with portrait filters, HD MP4 selection, and landscape fallback."""

    BASE_URL = "https://api.pexels.com/videos/search"

    def __init__(self, api_key: Optional[str] = None, timeout: float = 15.0) -> None:
        self.api_key = api_key or os.getenv("PEXELS_API_KEY") or ""
        self.timeout = timeout

        self.session = requests.Session()
        retries = Retry(
            total=3,
            backoff_factor=1.0,
            status_forcelist=[429, 500, 502, 503, 504],
            allowed_methods=["GET"],
        )
        self.session.mount("https://", HTTPAdapter(max_retries=retries))

    def _headers(self) -> Dict[str, str]:
        if not self.api_key:
            raise ValueError(
                "PEXELS_API_KEY is not set. Please add it to your .env file or pass api_key."
            )
        return {"Authorization": self.api_key}

    def search_video(
        self,
        query: str,
        orientation: str = "portrait",
        per_page: int = 5,
    ) -> Tuple[Optional[PexelsVideo], bool]:
        """Search Pexels for a query with portrait priority and landscape fallback.

        Returns:
            Tuple of (PexelsVideo or None, was_fallback_boolean)
        """
        # Step 1: Search preferred orientation (portrait)
        videos, was_fallback = self._execute_search(query, orientation=orientation, per_page=per_page)
        
        # Step 2: Fallback to landscape if 0 results
        if not videos and orientation == "portrait":
            videos, _ = self._execute_search(query, orientation="landscape", per_page=per_page)
            was_fallback = True

        # Step 3: Fallback to no orientation filter if still 0 results
        if not videos:
            videos, _ = self._execute_search(query, orientation=None, per_page=per_page)
            was_fallback = True

        # Step 4: Fallback to simplified query (first 2 words) if still 0
        if not videos:
            simplified_query = " ".join(query.split()[:2])
            if simplified_query and simplified_query != query:
                videos, _ = self._execute_search(simplified_query, orientation=None, per_page=per_page)
                was_fallback = True

        if not videos:
            return None, was_fallback

        # Re-rank and extract the best MP4 file from the top matching video
        best_video = self._select_best_video(videos, target_portrait=(orientation == "portrait"))
        if best_video:
            best_video.was_fallback = was_fallback

        return best_video, was_fallback

    def mock_video(self, query: str, clip_index: int = 1) -> Tuple[PexelsVideo, bool]:
        """Return simulated portrait HD video result for offline testing."""
        sample_file = VideoFileCandidate(
            id=1000 + clip_index,
            quality="hd",
            file_type="video/mp4",
            width=1080,
            height=1920,
            fps=30.0,
            link=f"https://static.pexels.com/mock/clip_{clip_index:02d}_1080x1920.mp4",
        )
        video = PexelsVideo(
            id=2000 + clip_index,
            url=f"https://www.pexels.com/video/{2000 + clip_index}/",
            duration=15,
            tags=query.split(),
            user_name="StockCinematographer",
            selected_file=sample_file,
            was_fallback=False,
        )
        return video, False

    def _execute_search(
        self,
        query: str,
        orientation: Optional[str] = None,
        per_page: int = 5,
    ) -> Tuple[List[Dict[str, Any]], bool]:
        """Execute HTTP GET to Pexels video search endpoint."""
        params: Dict[str, Any] = {"query": query, "per_page": per_page}
        if orientation:
            params["orientation"] = orientation

        try:
            resp = self.session.get(
                self.BASE_URL,
                headers=self._headers(),
                params=params,
                timeout=self.timeout,
            )
            resp.raise_for_status()
            data = resp.json()
            return data.get("videos", []), False
        except requests.RequestException as err:
            # Handle rate limit or network timeout
            if isinstance(err, requests.HTTPError) and err.response is not None and err.response.status_code == 401:
                raise ValueError("Invalid PEXELS_API_KEY. Please verify your Pexels credentials.") from err
            return [], False

    def _select_best_video(
        self,
        videos: List[Dict[str, Any]],
        target_portrait: bool = True,
    ) -> Optional[PexelsVideo]:
        """Select the highest resolution MP4 matching target orientation from candidate videos."""
        best_video_obj: Optional[PexelsVideo] = None
        highest_score = -1.0

        for vid in videos:
            video_id = vid.get("id", 0)
            url = vid.get("url", "")
            duration = int(vid.get("duration", 0))
            tags = [t.get("name", "") if isinstance(t, dict) else str(t) for t in vid.get("tags", [])]
            user = vid.get("user", {})
            user_name = user.get("name", "") if isinstance(user, dict) else ""

            # Evaluate video_files
            video_files = vid.get("video_files", [])
            best_file: Optional[VideoFileCandidate] = None
            best_file_score = -1.0

            for f in video_files:
                file_type = f.get("file_type", "")
                link = f.get("link", "")
                
                # Must be MP4
                if file_type != "video/mp4" and not link.endswith(".mp4"):
                    continue

                width = int(f.get("width") or 0)
                height = int(f.get("height") or 0)
                fps = float(f.get("fps") or 0.0)
                quality = str(f.get("quality") or "sd").lower()

                if width <= 0 or height <= 0 or not link:
                    continue

                # Scoring criteria:
                # 1. Aspect ratio: bonus if matches target orientation
                is_portrait = height >= width
                score = 0.0
                if target_portrait and is_portrait:
                    score += ORIENTATION_BONUS
                elif not target_portrait and not is_portrait:
                    score += ORIENTATION_BONUS

                # 2. Prefer the smallest file that still covers the render
                # target (1080x1920) over the largest one available: every
                # pixel above the target is downloaded, decoded and then
                # scaled away by the renderer, so "biggest wins" wastes
                # bandwidth/disk/time for no visual benefit.
                #
                # - At/above target: closer to the target (from above) is
                #   better. Score falls off monotonically as pixel_count
                #   grows past the target, so a smaller covering file always
                #   outscores a larger one, but the score is floored at
                #   _RESOLUTION_COVER_FLOOR so it can never sink into (let
                #   alone below) the undersized band.
                # - Below target: acceptable only when nothing covers the
                #   target; among those, bigger is better (less upscaling),
                #   but the whole band is capped by _RESOLUTION_UNDERSIZED_CEILING,
                #   which sits strictly below _RESOLUTION_COVER_FLOOR — so no
                #   undersized file can ever outscore a covering one.
                #
                # The resolution term's maximum (_RESOLUTION_COVER_CEILING)
                # plus the HD bonus is kept strictly below ORIENTATION_BONUS
                # (see the constants), so a correctly-oriented file always
                # beats a wrongly-oriented one regardless of resolution or
                # quality flag.
                pixel_count = width * height
                if pixel_count >= RENDER_TARGET_PIXELS:
                    coverage_ratio = RENDER_TARGET_PIXELS / pixel_count  # (0, 1], 1.0 = exact match
                    resolution_score = _RESOLUTION_COVER_FLOOR + (
                        _RESOLUTION_COVER_CEILING - _RESOLUTION_COVER_FLOOR
                    ) * coverage_ratio
                else:
                    undersize_ratio = pixel_count / RENDER_TARGET_PIXELS  # [0, 1)
                    resolution_score = _RESOLUTION_UNDERSIZED_CEILING * undersize_ratio
                score += resolution_score

                # 3. Quality flag bonus
                if quality == "hd":
                    score += _HD_QUALITY_BONUS

                if score > best_file_score:
                    best_file_score = score
                    best_file = VideoFileCandidate(
                        id=f.get("id", 0),
                        quality=quality,
                        file_type=file_type,
                        width=width,
                        height=height,
                        fps=fps,
                        link=link,
                    )

            if best_file and best_file_score > highest_score:
                highest_score = best_file_score
                best_video_obj = PexelsVideo(
                    id=video_id,
                    url=url,
                    duration=duration,
                    tags=tags,
                    user_name=user_name,
                    selected_file=best_file,
                )

        return best_video_obj


