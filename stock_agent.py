# Main Agent Orchestrator
# ============================================================================


class StockVideoMatcherAgent:
    """End-to-end AI-Powered Stock Video Matcher Agent."""

    def __init__(
        self,
        omniroute_base_url: Optional[str] = None,
        omniroute_api_key: Optional[str] = None,
        omniroute_model: Optional[str] = None,
        pexels_api_key: Optional[str] = None,
    ) -> None:
        self.query_generator = VisualQueryGenerator(
            base_url=omniroute_base_url,
            api_key=omniroute_api_key,
            model=omniroute_model,
        )
        self.pexels_fetcher = PexelsFetcher(api_key=pexels_api_key)
        self.downloader = ClipDownloader()

    def match(
        self,
        script_segment: str,
        duration_seconds: float,
        download: bool = False,
        output_dir: str = "output_clips",
        on_query_ready: Optional[Any] = None,
        mock: bool = False,
    ) -> StockMatcherResult:
        """Synchronously match stock footage to script segment.

        Args:
            script_segment: The voiceover narration text.
            duration_seconds: Runtime in seconds.
            download: If True, downloads MP4s to output_dir.
            output_dir: Folder to save downloaded MP4 clips.
            on_query_ready: Optional callback receiving generated queries.
            mock: If True, uses deterministic offline mock generation.

        Returns:
            StockMatcherResult containing all queries, matches, and file paths.
        """
        start_time = time.time()
        # output_dir is carried in a local and handed to each download_clip
        # call below; it is deliberately NOT stored on self.downloader.
        # match() is re-entrant: engine/pipeline.py builds ONE agent and
        # engine/media/clips.generate_plan_clips runs beats through a
        # 4-worker pool, and seconds pass between here and the downloads —
        # an LLM round trip plus a Pexels search per clip. Recording the
        # destination on the shared downloader therefore meant a beat
        # downloaded into whichever directory the most recently *started*
        # call had asked for, not its own: clip_NN.mp4 names collided
        # across beats again, and the clip_NN.mp4.tmp staging path raced,
        # so a half-written file could be renamed over a finished one.
        # Nothing here may mutate self (or anything reachable from it).

        # 1. Generate queries via OmniRoute or Mock
        if mock:
            queries, clip_count = self.query_generator.generate_mock_queries(
                script_segment=script_segment,
                duration_seconds=duration_seconds,
            )
        else:
            queries, clip_count = self.query_generator.generate_queries(
                script_segment=script_segment,
                duration_seconds=duration_seconds,
            )

        if on_query_ready:
            on_query_ready(queries)

        matches: List[ClipMatch] = []

        # 2. Fetch stock videos for each query
        for query in queries:
            try:
                if mock or not self.pexels_fetcher.api_key:
                    matched_video, was_fallback = self.pexels_fetcher.mock_video(
                        query=query.search_query,
                        clip_index=query.clip_index,
                    )
                else:
                    matched_video, was_fallback = self.pexels_fetcher.search_video(
                        query=query.search_query,
                        orientation="portrait",
                        per_page=5,
                    )
                match_entry = ClipMatch(
                    clip_index=query.clip_index,
                    query=query,
                    video=matched_video,
                    error=None if matched_video else "No stock video found for query",
                )
            except Exception as exc:
                match_entry = ClipMatch(
                    clip_index=query.clip_index,
                    query=query,
                    video=None,
                    error=str(exc),
                )
            matches.append(match_entry)

        # 3. Optional download pipeline
        if download:
            for match in matches:
                if match.video and match.video.selected_file:
                    try:
                        saved_path = self.downloader.download_clip(
                            url=match.video.selected_file.link,
                            clip_index=match.clip_index,
                            output_dir=output_dir,
                        )
                        match.download_path = str(saved_path)
                    except Exception as err:
                        match.error = f"Download failed: {err}"

        elapsed = time.time() - start_time
        return StockMatcherResult(
            script_segment=script_segment,
            duration_seconds=duration_seconds,
            clip_count=clip_count,
            model_used=self.query_generator.model if not mock else "mock-generator",
            matches=matches,
            execution_time_seconds=elapsed,
        )

    async def match_async(
        self,
        script_segment: str,
        duration_seconds: float,
        download: bool = False,
        output_dir: str = "output_clips",
        mock: bool = False,
    ) -> StockMatcherResult:
        """Asynchronously execute matching via asyncio thread pool."""
        return await asyncio.to_thread(
            self.match,
            script_segment=script_segment,
            duration_seconds=duration_seconds,
            download=download,
            output_dir=output_dir,
            mock=mock,
        )


