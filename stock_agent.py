def render_rich_output(
    console: Console,
    result: StockMatcherResult,
    show_downloads: bool = False,
) -> None:
    """Render a polished, executive-ready terminal display using Rich."""
    try:
        # Header Banner
        banner = Panel(
            f"[bold cyan]AI-Powered Stock Video Matcher[/bold cyan]\n"
            f"[dim]OmniRoute Gateway ({result.model_used}) + Pexels HD Portrait API[/dim]",
            border_style="cyan",
            expand=False,
        )
        console.print(banner)

        # Input Summary Table
        summary_table = Table(show_header=False, box=None, padding=(0, 2))
        summary_table.add_column("Key", style="bold yellow")
        summary_table.add_column("Value", style="white")

        script_preview = (
            result.script_segment[:90] + "..."
            if len(result.script_segment) > 90
            else result.script_segment
        )
        summary_table.add_row("Script Segment", f'"{script_preview}"')
        summary_table.add_row("Duration", f"{result.duration_seconds:.1f}s")
        summary_table.add_row("Pacing Formula", f"ceil({result.duration_seconds:.1f} / 2.5) = {result.clip_count} cuts")
        summary_table.add_row("Execution Time", f"{result.execution_time_seconds:.2f}s")
        console.print(Panel(summary_table, title="Input & Pacing Overview", border_style="dim"))

        # Results Table
        results_table = Table(
            title="[bold green]Matched Stock Video Timeline[/bold green]",
            border_style="blue",
            header_style="bold magenta",
            expand=True,
        )
        results_table.add_column("#", style="cyan", width=4, justify="center")
        results_table.add_column("Visual Search Query", style="bold white", width=26)
        results_table.add_column("Shot Intent", style="italic dim", width=28)
        results_table.add_column("Status / Fallback", style="yellow", width=18)
        results_table.add_column("Resolution", style="green", width=12)
        results_table.add_column("Pexels Link / Local File", style="blue")

        for m in result.matches:
            idx_str = f"{m.clip_index:02d}"
            query_str = m.query.search_query
            intent_str = m.query.shot_intent

            if m.video and m.video.selected_file:
                file_meta = m.video.selected_file
                status_str = "[green][OK] Portrait[/green]" if not m.video.was_fallback else "[yellow][FALLBACK] Landscape[/yellow]"
                res_str = f"{file_meta.resolution} ({file_meta.quality.upper()})"
                
                if m.download_path:
                    link_display = f"[bold green]Saved:[/bold green] {m.download_path}"
                else:
                    link_display = f"{file_meta.link[:35]}... (Pexels #{m.video.id})"
            else:
                status_str = "[red][FAIL][/red]"
                res_str = "N/A"
                link_display = f"[red]{m.error or 'Not found'}[/red]"

            results_table.add_row(idx_str, query_str, intent_str, status_str, res_str, link_display)

        console.print(results_table)
    except (UnicodeEncodeError, Exception):
        # Fallback to clean formatted JSON if terminal encoding fails
        print(result.to_json(indent=2))


